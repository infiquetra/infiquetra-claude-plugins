@dataclass(frozen=True)
class CompletionResult:
    row_id: str
    verified: bool
    reason: str
    detail: str
    predicate: PredicateOutcome | None = None
    scope: session_lifecycle.ScopeCheck | None = None
    artifact_digest: str | None = None
    artifact_path: str | None = None
    integration: str | None = None
    depth_sample: DepthSample | None = None

    def to_mapping(self) -> dict[str, Any]:
        return {
            "result": "verified" if self.verified else "failed",
            "reason": self.reason,
            "detail": self.detail,
            "predicate": self.predicate.to_mapping() if self.predicate is not None else None,
            "artifact_digest": self.artifact_digest,
            "artifact_path": self.artifact_path,
            "integration": self.integration,
            # The verifier's identity, the claims it sampled, where it checked each one, and how
            # it disposed of them. Without this a child that was genuinely sampled and one whose
            # sample certified nothing are the same green row, and the pass becomes its own
            # evidence -- which is the exact failure this unit exists to prevent.
            "depth_sample": self.depth_sample.to_mapping() if self.depth_sample else None,
            "at": time.time(),
        }


def _record(root: Path, row_id: str, result: CompletionResult) -> CompletionResult:
    """Write the durable verdict, and keep ``phase`` honest about it.

    The verdict lives in its own ``completion`` key rather than in ``observed_state``.
    ``observed_state`` is owned by the liveness detectors: the subscriber's snapshot catch-up
    rewrites it for every row with a live pane, so a failure recorded only there is erased the
    next time catch-up runs while the child's pane is still open.

    The invariant this function maintains is: **a row's phase is ``verified`` if and only if its
    latest completion verdict is a pass.**  Both halves matter, and the second one is not
    optional now that re-evaluation is a specified behaviour rather than a hypothetical -- the
    catch-up contract re-evaluates run-bound artifacts and predicates on every startup and
    reconnect.  A row that passed once and fails its re-evaluation would otherwise end with
    ``phase="verified"`` and ``completion.result="failed"``, and U4's reap gate reads the phase:
    the contradiction would be consumed as a pass.

    A failing verdict therefore leaves the row at ``working`` -- by leaving the phase untouched
    for a first evaluation, or by demoting it from ``verified`` for a re-evaluation.  Both are the
    same rule, and neither invents a phase: ``PHASES`` is a closed, operator-approved vocabulary
    with no member meaning "evaluated and failed", and "evaluated and failed" is already
    representable as ``phase="working"`` plus a recorded failure, which is what
    :func:`is_working_not_failed` and :func:`failed_rows` read.  A ``reaped`` row is past this
    question and is left alone.

    The ``artifact_path`` *column* is deliberately not written here.  It has exactly one owner --
    :func:`settle_artifact`, the moment the fact becomes true -- because two writers of one column
    is how a column ends up meaning whatever the last writer thought it meant.  The path is still
    part of this verdict's own record, inside the ``completion`` mapping.
    """
    fields: dict[str, Any] = {"completion": result.to_mapping()}
    if result.verified:
        fields["phase"] = "verified"
        fields["expected_state"] = "verified"
    elif register_store.read_rows(root).get(row_id, {}).get("phase") == "verified":
        fields["phase"] = "working"
        fields["expected_state"] = "working"
    register_store.upsert_row(root, row_id, fields)
    return result


def evaluate_completion(
    root: Path,
    spec: session_lifecycle.ChildSpec,
    landing: session_lifecycle.Landing,
    changed_paths_baseline: session_lifecycle.ChangedPathsBaseline,
    receipt: DispatchReceipt,
    *,
    git: session_lifecycle.GitLanding,
    depth_sample: DepthSample | Mapping[str, Any] | None = None,
) -> CompletionResult:
    """Decide whether one child reaches ``verified``, and record why either way.

    Safe to call more than once for one dispatch, which is what makes both the restart path and
    judgment-shaped work reachable.  Settlement replays from its durable record instead of
    consuming the in-flight file a second time (see :func:`settle_artifact`), so the sequence for
    judgment work is: evaluate once and get ``depth_sample_missing`` with the artifact now settled
    at a recorded digest; dispatch an independent verifier against that settled path; evaluate
    again with its sample.  The second call re-runs the mechanical controls rather than trusting
    the first call's verdict, so the answer is a fresh one, not a cached one.
    """
    landing_cwd = Path(landing.cwd)
    state: dict[str, Any] = {}

    def fail(reason: str, detail: str, **fields: Any) -> CompletionResult:
        return _record(
            root,
            spec.row_id,
            CompletionResult(spec.row_id, False, reason, detail, **{**state, **fields}),
        )

    # The receipt, the specification, the landing and the baseline arrive as four independent
    # arguments and every outcome is recorded under the specification's row. Nothing else in this
    # function would notice if they described different children, so a correctly bound artifact
    # for one child could verify another child's row.
    mismatches = [
        f"{label}: spec {mine!r} != receipt {theirs!r}"
        for label, mine, theirs in (
            ("run_id", spec.run_id, receipt.run_id),
            ("row_id", spec.row_id, receipt.row_id),
            ("landing", str(landing_cwd.resolve()), str(Path(receipt.landing_cwd).resolve())),
        )
        if mine != theirs
    ]
    if mismatches:
        return fail(
            "receipt_mismatch",
            "the dispatch receipt does not belong to the child being evaluated ("
            + "; ".join(mismatches)
            + "); evidence produced for one dispatch cannot verify another",
        )

    current_digest = closure_digest(landing_cwd, receipt.predicate, receipt.predicate_closure)
    if current_digest != receipt.predicate_digest:
        return fail(
            "predicate_tampered",
            "the predicate's dependency closure changed between dispatch and evaluation; "
            f"expected {receipt.predicate_digest}, found {current_digest}",
        )

    try:
        settlement = settle_artifact(root, receipt)
    except (ArtifactError, ReceiptAuthenticationError) as exc:
        # An unauthenticated settlement record is recorded as a refusal rather than raised. A
        # control that raises instead of recording leaves the register showing a working child
        # with no verdict, which is a fail-open one level up.
        return fail("artifact_unsettled", str(exc))
    artifact = Path(settlement.artifact_path)
    state["artifact_path"] = settlement.artifact_path

    try:
        state["artifact_digest"] = assert_artifact_binding(artifact, receipt)
    except ArtifactError as exc:
        return fail("artifact_binding", str(exc))
    artifact_digest = str(state["artifact_digest"])

    artifacts_dir = artifact_landing(landing_cwd, receipt.run_id, receipt.row_id)
    observer_baseline = git.changed_paths_baseline(
        landing_cwd,
        base_commit=landing.base_commit,
        ambient_root=landing.ambient_root,
    )
    artifacts_before = _artifact_fingerprints(artifacts_dir)
    outcome = run_predicate(receipt.predicate, workdir=landing_cwd)
    state["predicate"] = outcome
    disturbed = _predicate_side_effects(
        landing, observer_baseline, artifacts_before, artifacts_dir=artifacts_dir, git=git
    )
    if disturbed:
        return fail(
            "predicate_side_effect",
            "the predicate changed the child's landing or its evidence while evaluating it, so "
            "what is on disk is no longer what was bound: " + ", ".join(sorted(disturbed)),
        )

    try:
        state["scope"] = session_lifecycle.check_completion_scope(
            repository_scope_for(spec),
            landing,
            changed_paths_baseline,
            predicate_passed=outcome.passed,
            git=git,
        )
    except session_lifecycle.ScopeViolationError as exc:
        return fail("scope_violation", str(exc))

    if not outcome.passed:
        return fail(
            outcome.reason,
            f"predicate {list(receipt.predicate.argv)} did not pass: {outcome.reason}",
        )

    try:
        state["integration"] = verify_integration(receipt, landing, git=git)
    except CompletionError as exc:
        return fail("integration_unverified", str(exc))

    sample, depth_failure = _depth_verdict(
        root, spec, depth_sample, artifact_digest=artifact_digest
    )
    state["depth_sample"] = sample
    if depth_failure is not None:
        return fail(*depth_failure)

    return _record(
        root,
        spec.row_id,
        CompletionResult(
            spec.row_id,
            True,
            "verified",
            f"settled, run-bound artifact {receipt.artifact_relpath} passed "
            f"{list(receipt.predicate.argv)}; {state['integration']}",
            **state,
        ),
    )


def _artifact_fingerprints(artifacts_dir: Path) -> tuple[tuple[str, str], ...]:
    """Digest every file in the child's exclusive artifact directory.

    The Git snapshot cannot see this directory at all -- it is *required* to be invisible to the
    boundary, which is the entire basis of the read-only sibling repair -- so the observer whose
    job is "the predicate must not disturb the evidence" has to observe the evidence directly or
    it is not observing the evidence at all.  The whole directory rather than the one artifact,
    because a predicate that rewrites the in-flight sibling of the next dispatch is the same
    defect wearing a different filename.
    """
    if not artifacts_dir.is_dir():
        return ()
    entries: list[tuple[str, str]] = []
    for path in sorted(artifacts_dir.rglob("*")):
        relative = path.relative_to(artifacts_dir).as_posix()
        if path.is_symlink():
            entries.append((relative, "symlink:" + os.readlink(path)))
        elif path.is_file():
            entries.append((relative, str(_path_state(path).get("digest"))))
    return tuple(entries)


def _predicate_side_effects(
    landing: session_lifecycle.Landing,
    observer_baseline: session_lifecycle.ChangedPathsBaseline,
    artifacts_before: Sequence[tuple[str, str]],
    *,
    artifacts_dir: Path,
    git: session_lifecycle.GitLanding,
) -> set[str]:
    """Everything the predicate itself touched: repository-visible paths, and the evidence.

    Compared against snapshots taken immediately before the predicate ran, so anything reported
    here was authored by the check and not by the child.  Three surfaces, because the check can
    reach all three: the child's landing, the ambient checkout (a mutating child's predicate runs
    in its worktree while the ambient tree is observed separately), and the Git-invisible artifact
    directory.

    What is still **not** observed: Git-ignored paths outside the artifact directory, including
    ``.orchestrate/register.json`` itself.  A predicate that rewrites the register is not caught
    here -- it is caught by the register's records being authenticated, which is a different
    control with a different mechanism, stated in ``references/predicates.md``.
    """
    after = git.changed_paths_baseline(
        Path(landing.cwd),
        base_commit=landing.base_commit,
        ambient_root=landing.ambient_root,
    )
    prefix = artifacts_dir.name
    artifact_changes = {
        f"{prefix}/{name}"
        for name in _differences(artifacts_before, _artifact_fingerprints(artifacts_dir))
    }
    return (
        _differences(observer_baseline.fingerprints, after.fingerprints)
        | _differences(observer_baseline.ambient_fingerprints, after.ambient_fingerprints)
        | artifact_changes
    )


def _differences(before: Sequence[tuple[str, str]], after: Sequence[tuple[str, str]]) -> set[str]:
    before_map = dict(before)
    after_map = dict(after)
    return {
        path
        for path in set(before_map) | set(after_map)
        if before_map.get(path) != after_map.get(path)
    }


def _depth_verdict(
    root: Path,
    spec: session_lifecycle.ChildSpec,
    depth_sample: DepthSample | Mapping[str, Any] | None,
    *,
    artifact_digest: str,
) -> tuple[DepthSample | None, tuple[str, str] | None]:
    """Judgment-shaped work cannot reach verified on mechanical coverage alone.

    Returns the parsed sample -- so the caller can put it on the record whichever way the verdict
    goes -- alongside the failure, if any.  Every parse and validation error is converted into a
    recorded failure here rather than raised, because the caller is the only thing that writes to
    the register: an exception escaping this function leaves a child that looks like it is still
    working when in fact it was evaluated and refused.
    """
    if not is_judgment_shaped(spec.work_shape):
        return None, None
    if depth_sample is None:
        return None, (
            "depth_sample_missing",
            f"work shape {spec.work_shape!r} is judgment-shaped, so a passing mechanical "
            "predicate is not sufficient; an independent verifier's depth sample is required",
        )
    try:
        sample = (
            depth_sample
            if isinstance(depth_sample, DepthSample)
            else DepthSample.from_mapping(depth_sample)
        )
    except DepthSampleError as exc:
        return None, ("depth_sample_invalid", str(exc))
    try:
        sample.validate(
            root=root,
            child_row_id=spec.row_id,
            run_id=spec.run_id,
            artifact_digest=artifact_digest,
        )
    except DepthSampleError as exc:
        return sample, ("depth_sample_invalid", str(exc))
    unsupported = [claim for claim in sample.claims if claim.disposition == "unsupported"]
    if unsupported:
        return sample, (
            "depth_sample_unsupported",
            "the independent verifier could not support "
            + "; ".join(f"{claim.claim!r} at {claim.evidence_location}" for claim in unsupported),
        )
    if not any(claim.disposition == "supported" for claim in sample.claims):
        # A sample whose every claim came back "inconclusive" established nothing. Treating the
        # absence of a refutation as a confirmation is how an independent read becomes a
        # formality, and it is indistinguishable downstream from a real one.
        return sample, (
            "depth_sample_inconclusive",
            f"the independent verifier sampled {len(sample.claims)} claim(s) and could support "
            "none of them; a sample that established nothing does not certify judgment work",
        )
    return sample, None


def read_receipt(root: Path, row_id: str) -> DispatchReceipt:
    """Load and authenticate the receipt this dispatch established.

    This is the only path a restarted orchestrator has to the expected evidence identity, and it
    reads that identity out of a Git-ignored file the child can write.  The authentication is
    therefore not a formality: without it a child plants whatever binding token or predicate it
    can already satisfy and then satisfies it.  Failing here is a refusal to complete, which is
    the correct outcome -- a receipt that cannot be authenticated establishes nothing, and a child
    with no establishable expected identity has no way to be verified.
    """
    row = register_store.read_rows(root).get(row_id)
    if row is None:
        raise CompletionError(f"unknown child row {row_id!r}")
    stored = row.get(DISPATCH_RECEIPT_KEY)
    if not isinstance(stored, Mapping):
        raise CompletionError(
            f"child {row_id!r} has no dispatch receipt; it was never bound to a dispatch and "
            "cannot be completed"
        )
    claimed_run = stored.get("run_id")
    if not isinstance(claimed_run, str) or not claimed_run:
        raise ReceiptAuthenticationError(
            f"the dispatch receipt stored for {row_id!r} names no run and cannot be authenticated"
        )
    # The run_id comes from the untrusted record, but naming a different run only changes *which*
    # secret the digest must have been produced under -- never whether one is needed. ``create``
    # is off so a record naming a run this host never issued fails instead of minting a key.
    secret = run_secret(root, claimed_run, create=False)
    return DispatchReceipt.from_mapping(_unseal(stored, secret, label="dispatch receipt"))


def completion_record(root: Path, row_id: str) -> dict[str, Any] | None:
    """The operator-facing verdict for one row, or ``None`` when it has not been evaluated."""
    row = register_store.read_rows(root).get(row_id)
    if row is None:
        return None
    record = row.get("completion")
    return dict(record) if isinstance(record, Mapping) else None


def is_working_not_failed(root: Path, row_id: str) -> bool:
    """True when a row is still working rather than carrying a recorded failure.

    ``PHASES`` has no member for "evaluated and failed", so this is how the operator's view keeps
    the two apart without inventing one.
    """
    record = completion_record(root, row_id)
    return record is None or record.get("result") != "failed"


def failed_rows(root: Path, *, run_id: str | None = None) -> dict[str, dict[str, Any]]:
    """Every row whose recorded verdict is a failure -- the operator's "what stalled" view."""
    rows = register_store.read_rows(root, run_id=run_id)
    failed: dict[str, dict[str, Any]] = {}
    for row_id, row in rows.items():
        record = row.get("completion")
        if isinstance(record, Mapping) and record.get("result") == "failed":
            failed[row_id] = dict(record)
    return failed
