# --------------------------------------------------------------------------- predicate schema


@dataclass(frozen=True)
class PredicateSpec:
    """A bounded mechanical check declared as a fixed argument vector.

    The schema is *closed*: an unknown key is an error rather than an ignored field, because a
    silently ignored ``shell`` or ``timeout`` key is exactly how an unbounded check reaches
    production looking bounded.
    """

    argv: tuple[str, ...]
    timeout_seconds: float = DEFAULT_TIMEOUT_SECONDS
    max_output_bytes: int = DEFAULT_MAX_OUTPUT_BYTES

    ALLOWED_KEYS = ("argv", "timeout_seconds", "max_output_bytes")

    def __post_init__(self) -> None:
        if not self.argv:
            raise PredicateSchemaError("predicate argv must contain at least the program")
        for item in self.argv:
            if not isinstance(item, str) or not item:
                raise PredicateSchemaError(
                    "every predicate argv element must be a non-empty string"
                )
        program = PurePosixPath(self.argv[0]).name
        if program in _INDIRECTION_WRAPPERS:
            raise PredicateSchemaError(
                f"predicate program {self.argv[0]!r} launches another program; name the real "
                "program directly so its dependency closure can be established"
            )
        if program in _SHELLS:
            raise PredicateSchemaError(
                f"predicate program {self.argv[0]!r} is a shell; a predicate is an argument "
                "vector, not shell text"
            )
        if any(flag in _TEXT_EXECUTION_FLAGS for flag in self.argv[1:]):
            raise PredicateSchemaError(
                "predicate argv carries an inline-source flag "
                f"({sorted(_TEXT_EXECUTION_FLAGS)}); a predicate must be a program and its "
                "arguments, so its dependency closure can be established"
            )
        if not 0 < self.timeout_seconds <= MAX_TIMEOUT_SECONDS:
            raise PredicateSchemaError(
                f"predicate timeout_seconds must be in (0, {MAX_TIMEOUT_SECONDS}]"
            )
        if not 0 < self.max_output_bytes <= MAX_OUTPUT_BYTES:
            raise PredicateSchemaError(
                f"predicate max_output_bytes must be in (0, {MAX_OUTPUT_BYTES}]"
            )

    @classmethod
    def from_mapping(cls, value: Any) -> PredicateSpec:
        """Build a spec from a register/JSON declaration, rejecting anything else."""
        if isinstance(value, str):
            raise PredicateSchemaError(
                "a predicate declared as text is rejected; declare an 'argv' array so the check "
                "runs without a shell and its dependency closure can be established"
            )
        if not isinstance(value, Mapping):
            raise PredicateSchemaError("a predicate declaration must be a JSON object")
        unknown = sorted(set(value) - set(cls.ALLOWED_KEYS))
        if unknown:
            raise PredicateSchemaError(
                f"unknown predicate keys {unknown}; the schema is closed and allows "
                f"{list(cls.ALLOWED_KEYS)}"
            )
        argv = value.get("argv")
        if isinstance(argv, str):
            raise PredicateSchemaError(
                "predicate argv must be an array of arguments, not a command string"
            )
        if not isinstance(argv, Sequence):
            raise PredicateSchemaError("predicate argv must be an array of arguments")
        timeout = value.get("timeout_seconds", DEFAULT_TIMEOUT_SECONDS)
        output_cap = value.get("max_output_bytes", DEFAULT_MAX_OUTPUT_BYTES)
        if isinstance(timeout, bool) or not isinstance(timeout, int | float):
            raise PredicateSchemaError("predicate timeout_seconds must be a number")
        if isinstance(output_cap, bool) or not isinstance(output_cap, int):
            raise PredicateSchemaError("predicate max_output_bytes must be an integer")
        return cls(tuple(argv), float(timeout), int(output_cap))

    def to_mapping(self) -> dict[str, Any]:
        return {
            "argv": list(self.argv),
            "timeout_seconds": self.timeout_seconds,
            "max_output_bytes": self.max_output_bytes,
        }


# --------------------------------------------------------------------------- closure analysis


def _repo_relative(workdir: Path, path: Path) -> str | None:
    try:
        return path.resolve().relative_to(workdir.resolve()).as_posix()
    except ValueError:
        return None


#: Suffixes of an importable module file.  Native extensions are included so an in-tree ``.so``
#: at least enters the closure and is digested, even though nothing can follow *its* imports.
_MODULE_SUFFIXES = (".py", ".so", ".pyd")


def _module_candidates(module: str, search_roots: Sequence[Path]) -> list[Path]:
    """Every in-tree file Python would execute to satisfy ``import module``.

    That includes each **parent package initializer** along the dotted path, not just the leaf.
    For ``import pkg.oracle`` Python executes ``pkg/__init__.py`` before ``pkg/oracle.py``, so a
    closure holding only the leaf lets a child whose scope is exactly ``pkg/__init__.py`` change
    what ``pkg.oracle`` resolves to -- in scope, with the closure digest unchanged.  A package
    with no initializer (PEP 420 namespace package) simply contributes no such file, which is why
    the candidates are filtered by existence rather than required to exist.
    """
    parts = module.split(".")
    candidates: list[Path] = []
    for root in search_roots:
        for depth in range(1, len(parts)):
            candidates.append(root.joinpath(*parts[:depth]) / "__init__.py")
        base = root.joinpath(*parts)
        for suffix in _MODULE_SUFFIXES:
            candidates.append(base.with_suffix(suffix))
        candidates.append(base / "__init__.py")
    return candidates


def _relative_package_root(source: Path, level: int) -> Path:
    root = source.parent
    for _ in range(level - 1):
        root = root.parent
    return root


def _imported_files(source: Path, workdir: Path) -> set[Path]:
    """Resolve one Python file's static imports to files inside ``workdir``.

    Only statements the parser can see are followed.  Everything a module reaches by dynamic
    import, ``sys.path`` manipulation, or data-file read is outside this analysis and is declared
    as such in ``references/predicates.md``.
    """
    try:
        tree = ast.parse(source.read_text(encoding="utf-8", errors="replace"), filename=str(source))
    except SyntaxError as exc:
        raise PredicateClosureError(
            f"predicate closure member {source} does not parse: {exc}"
        ) from exc
    found: set[Path] = set()
    for node in ast.walk(tree):
        candidates: list[Path] = []
        if isinstance(node, ast.Import):
            for alias in node.names:
                candidates.extend(_module_candidates(alias.name, (source.parent, workdir)))
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                package_root = _relative_package_root(source, node.level)
                roots: tuple[Path, ...] = (package_root,)
            else:
                roots = (source.parent, workdir)
            if node.module:
                candidates.extend(_module_candidates(node.module, roots))
            for alias in node.names:
                name = f"{node.module}.{alias.name}" if node.module else alias.name
                candidates.extend(_module_candidates(name, roots))
        for candidate in candidates:
            if candidate.is_file() and _repo_relative(workdir, candidate) is not None:
                found.add(candidate.resolve())
    return found


def predicate_closure(
    workdir: Path,
    predicate: PredicateSpec,
    *,
    max_files: int = MAX_CLOSURE_FILES,
    subject: str | None = None,
) -> tuple[str, ...]:
    """Return every file inside ``workdir`` the predicate is known to depend on.

    Roots are the argument-vector elements that resolve to a real path inside ``workdir`` -- both
    the entry-point script and path arguments such as a test file or directory, because for a
    runner like ``pytest`` the arguments *are* the check.  Python roots are then followed through
    their static import statements, transitively.

    ``subject`` is the artifact under judgement.  It is data the check reads, not code that
    decides what the check does, so it is excluded from the closure -- otherwise every predicate
    would be rejected for depending on the very file it exists to inspect.  A predicate that
    *executes* its subject is refused outright, and a predicate that statically imports it is
    still caught, because the import is discovered from another closure member.

    Bounded on purpose: exceeding ``max_files`` or the byte cap raises rather than truncating,
    because a silently truncated closure is a control that reports a narrower dependency set than
    the real one.
    """
    workdir = workdir.resolve()
    if subject is not None and PurePosixPath(predicate.argv[0]) == PurePosixPath(subject):
        raise PredicateClosureError(
            f"predicate program {predicate.argv[0]!r} is the artifact it judges; a check the "
            "child authors is not a check"
        )
    pending: list[Path] = []
    for item in predicate.argv:
        if item.startswith("-") or (subject is not None and item == subject):
            continue
        candidate = (workdir / item).resolve()
        if _repo_relative(workdir, candidate) is None or not candidate.exists():
            continue
        if candidate.is_dir():
            members = sorted(candidate.rglob("*.py"))
            if len(members) > max_files:
                raise PredicateClosureError(
                    f"predicate path argument {item!r} expands to {len(members)} Python files, "
                    f"above the {max_files}-file closure bound"
                )
            pending.extend(members)
        else:
            pending.append(candidate)

    seen: set[Path] = set()
    total_bytes = 0
    while pending:
        current = pending.pop()
        if current in seen:
            continue
        seen.add(current)
        if len(seen) > max_files:
            raise PredicateClosureError(
                f"predicate dependency closure exceeds {max_files} files; declare a narrower "
                "predicate rather than accepting an unbounded closure"
            )
        total_bytes += current.stat().st_size
        if total_bytes > MAX_CLOSURE_BYTES:
            raise PredicateClosureError(
                f"predicate dependency closure exceeds {MAX_CLOSURE_BYTES} bytes"
            )
        if current.suffix == ".py":
            pending.extend(_imported_files(current, workdir))

    relative = {_repo_relative(workdir, path) for path in seen}
    return tuple(sorted(item for item in relative if item is not None))


def closure_digest(workdir: Path, predicate: PredicateSpec, closure: Sequence[str]) -> str:
    """Digest the predicate declaration together with the contents of its closure."""
    digest = hashlib.sha256()
    digest.update(json.dumps(predicate.to_mapping(), sort_keys=True).encode("utf-8"))
    for relative in sorted(closure):
        digest.update(b"\0" + relative.encode("utf-8") + b"\0")
        path = workdir / relative
        if not path.is_file():
            digest.update(b"missing")
            continue
        with path.open("rb") as stream:
            while chunk := stream.read(1024 * 1024):
                digest.update(chunk)
    return "sha256:" + digest.hexdigest()


def assert_predicate_outside_write_scope(
    closure: Sequence[str], write_scope: Sequence[str]
) -> None:
    """Refuse a predicate the child it certifies could rewrite.

    ``write_scope`` is every location the child may write: its declared repository scope when it
    is a mutating child, plus its own exclusive artifact landing in every case.  Checking only the
    entry-point path would leave a predicate that *imports* a module inside the scope exactly as
    compromised as one that lives there.
    """
    normalized = session_lifecycle.normalize_scope(write_scope)
    inside = sorted(path for path in closure if session_lifecycle.path_in_scope(path, normalized))
    if inside:
        raise PredicateScopeError(
            "predicate dependency closure lives inside the child's write scope and could be "
            "weakened by the child it certifies: " + ", ".join(inside)
        )


# --------------------------------------------------------------------------- authentication


def _safe_component(value: str, *, label: str) -> str:
    if not value or not _SAFE_COMPONENT_RE.match(value):
        raise CompletionError(f"{label} {value!r} must be a non-empty [A-Za-z0-9._-]+ token")
    return value


def run_secret_dir() -> Path:
    """Where this host keeps per-run orchestrator secrets."""
    override = os.environ.get(RUN_SECRET_DIR_ENV)
    directory = (
        Path(override).expanduser().resolve()
        if override
        else DEFAULT_RUN_SECRET_DIR.expanduser().resolve()
    )
    register_store._refuse_default_host_dir_under_pytest(directory, label="run-secret")
    return directory


def forget_run_secret(run_id: str) -> None:
    """Delete this run's host-local secret so a later reuse does not inherit identity."""
    path = run_secret_dir() / f"{_safe_component(run_id, label='run_id')}.key"
    with contextlib.suppress(FileNotFoundError):
        path.unlink()


def run_secret(root: Path, run_id: str, *, create: bool = True) -> bytes:
    """Load -- or, for a new run, mint -- the secret that authenticates this run's durable records.

    **The threat this defeats.**  The live register is addressed by ``run_id`` outside every
    landing, so a sandboxed child cannot rewrite a receipt by writing files in its working
    directory.  Two runtimes -- Claude and Muse -- expose no workspace-write flag, so they can
    still reach the host-local directory if they know the path.  A child that replaces the
    binding token with one it already holds, or replaces the predicate with ``/usr/bin/true``
    and recomputes the closure digest so the tamper check agrees, would satisfy a receipt it
    wrote itself.  Both were demonstrated against this module when the live file still sat
    inside the landing.

    Inspection cannot close that, because a forged record and a genuine one are the same bytes in
    the same place.  Authentication can, **against a party that cannot read the key.**  The key
    never enters any child's landing.  Mode ``0600`` excludes other operating-system accounts.
    It does not exclude a child running as this account.  For runtimes whose sandbox does not
    deny ``~/.orchestrate``, this module does not defend against a child that reads the run
    key and seals payloads that verify.  A child that can reach the host path can also
    *destroy* the receipt -- and then nothing verifies, which is the correct failure.

    **What the key rests on.**  The secret lives outside the repository, and that location is
    checked rather than assumed.  A workspace-write posture is the one containment the supported
    CLIs genuinely express.  Claude and Muse expose no such flag; the seal is not a defence
    against those runtimes reading the key.
    """
    directory = run_secret_dir().resolve()
    root_resolved = root.resolve()
    if directory == root_resolved or root_resolved in directory.parents:
        raise RunSecretError(
            f"the run-secret directory {directory} is inside the repository at {root_resolved}; "
            "every child's landing is inside that repository, so a secret stored there is "
            "writable by the very children it authenticates"
        )
    path = directory / f"{_safe_component(run_id, label='run_id')}.key"
    if path.exists():
        info = path.lstat()
        if stat_module.S_ISLNK(info.st_mode):
            raise RunSecretError(f"run secret {path} is a symlink; it must be a regular file")
        if info.st_mode & 0o077:
            raise RunSecretError(
                f"run secret {path} is accessible beyond its owner (mode "
                f"{stat_module.S_IMODE(info.st_mode):04o}); refusing to authenticate against a "
                "secret another account can read or replace"
            )
        material = path.read_bytes()
        if len(material) < RUN_SECRET_BYTES:
            raise RunSecretError(f"run secret {path} is shorter than {RUN_SECRET_BYTES} bytes")
        return material
    if not create:
        raise RunSecretError(
            f"no orchestrator secret exists for run {run_id!r} at {path}; a durable record "
            "claiming that run cannot be authenticated"
        )
    directory.mkdir(parents=True, exist_ok=True, mode=0o700)
    material = secrets.token_bytes(RUN_SECRET_BYTES)
    try:
        handle = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        # A concurrent orchestrator minted it first; its secret is the run's secret.
        return run_secret(root, run_id, create=False)
    try:
        os.write(handle, material)
        os.fsync(handle)
    finally:
        os.close(handle)
    return material


def _run_root_path(run_id: str) -> Path:
    return register_store.register_dir() / f"{_safe_component(run_id, label='run_id')}.root"


def record_run_root(root: Path, run_id: str) -> Path:
    """Record the work location this run was launched against.

    Provenance is the orchestrator's own root -- the first argument of
    :func:`session_lifecycle.launch_child` -- not a value derived from a landing.
    :func:`issue_receipt` never writes this file.  A later unit that issues before
    launching must call this first, with the same root it will pass to ``launch_child``.

    The live register is addressed by ``run_id``, not by this path.  This record is the
    work location (where git runs, where retirement archives) and the collision detector
    for two orchestrators that reuse one ``run_id`` against different checkouts.

    The file lives next to the live register, outside every repository, with the same
    permission rules as the run secret.  Writers of the same path share one exclusive
    lock and see a complete file or none; there is no empty-file window.  A second
    writer of a different path is a conflict, not a race.  Comparison is filesystem
    identity, not text equality of resolved strings.
    """
    directory = register_store.register_dir()
    root_resolved = Path(root).resolve()
    if directory == root_resolved or root_resolved in directory.parents:
        raise RunSecretError(
            f"the register directory {directory} is inside the repository at {root_resolved}; "
            "every child's landing is inside that repository, so a record stored there is "
            "writable by the very children it authenticates"
        )
    directory.mkdir(parents=True, exist_ok=True, mode=0o700)
    path = _run_root_path(run_id)
    lock_path = path.with_name(f"{path.name}.lock")
    lock_fd = os.open(lock_path, os.O_RDWR | os.O_CREAT, 0o600)
    try:
        fcntl.flock(lock_fd, fcntl.LOCK_EX)
        if path.exists():
            existing = _read_run_root_file(path)
            if not _same_recorded_root(existing, root_resolved):
                raise RunRootError(
                    f"run {run_id!r} is already recorded against {existing} and a second "
                    f"orchestrator claimed {root_resolved}; one run id has one register"
                )
            return existing
        tmp = path.with_name(f"{path.name}.{os.getpid()}.{time.monotonic_ns()}.tmp")
        payload = str(root_resolved).encode("utf-8")
        handle = -1
        handle = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        try:
            os.write(handle, payload)
            os.fsync(handle)
            os.close(handle)
            handle = -1
            os.replace(tmp, path)
        finally:
            if handle >= 0:
                os.close(handle)
            with contextlib.suppress(FileNotFoundError):
                tmp.unlink()
        return root_resolved
    finally:
        fcntl.flock(lock_fd, fcntl.LOCK_UN)
        os.close(lock_fd)


def _same_recorded_root(left: Path, right: Path) -> bool:
    try:
        return left.resolve().samefile(right.resolve())
    except OSError:
        return left.resolve() == right.resolve()


def _read_run_root_file(path: Path) -> Path:
    info = path.lstat()
    if stat_module.S_ISLNK(info.st_mode):
        raise RunRootError(f"run root {path} is a symlink; it must be a regular file")
    if info.st_mode & 0o077:
        raise RunRootError(
            f"run root {path} is accessible beyond its owner (mode "
            f"{stat_module.S_IMODE(info.st_mode):04o}); refusing to trust a record another "
            "account can read or replace"
        )
    material = path.read_bytes().decode("utf-8").strip()
    if not material:
        raise RunRootError(f"run root {path} is empty")
    return Path(material).resolve()


def read_run_root(run_id: str) -> Path | None:
    """The recorded register directory for this run, or ``None`` if none was recorded.

    Absence is not an error.  Issuance and evaluation then fall back to containment plus
    git identity, and they do not write this file -- writing it from a landing would
    canonise whatever store the first landing happened to name.
    """
    path = _run_root_path(run_id)
    if not path.exists():
        return None
    return _read_run_root_file(path)


def assert_store_is_this_runs_register(store: Path, run_id: str) -> None:
    """Refuse a store that is not the register directory recorded for this run.

    When no root was recorded, this is a no-op: containment and git identity still run,
    and this function does not mint a record from ``store``.  That residual is named on
    :func:`landing_root`.
    """
    recorded = read_run_root(run_id)
    resolved = Path(store).resolve()
    if recorded is not None and not _same_recorded_root(recorded, resolved):
        raise ReceiptRootError(
            f"the claimed store {resolved} is not the register directory recorded for "
            f"run {run_id!r} ({recorded})"
        )


def _signature(payload: Mapping[str, Any], secret: bytes) -> str:
    canonical = json.dumps(payload, sort_keys=True, separators=(",", ":"), default=str)
    return "hmac-sha256:" + hmac.new(secret, canonical.encode("utf-8"), hashlib.sha256).hexdigest()


def _seal(payload: Mapping[str, Any], secret: bytes) -> dict[str, Any]:
    """Return ``payload`` plus a keyed digest over exactly the fields it carries."""
    return {**payload, AUTHENTICATION_KEY: _signature(payload, secret)}


def _unseal(stored: Mapping[str, Any], secret: bytes, *, label: str) -> dict[str, Any]:
    """Return the authenticated fields of ``stored``, or refuse.

    The digest covers the stored mapping *as stored*, minus the signature itself, so a key added
    to the record is a mismatch rather than a field that is quietly ignored on the way back into
    a typed object.
    """
    presented = stored.get(AUTHENTICATION_KEY)
    payload = {key: value for key, value in stored.items() if key != AUTHENTICATION_KEY}
    if not isinstance(presented, str) or not presented:
        raise ReceiptAuthenticationError(
            f"the stored {label} carries no authentication; it was not written by an orchestrator "
            "that held this run's secret"
        )
    if not hmac.compare_digest(_signature(payload, secret), presented):
        raise ReceiptAuthenticationError(
            f"the stored {label} did not authenticate against this run's orchestrator secret; it "
            "was altered after it was written, or written by something that is not the "
            "orchestrator"
        )
    return payload


