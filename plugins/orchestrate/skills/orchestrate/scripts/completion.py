def artifact_binding_token(run_id: str, row_id: str, nonce: str) -> str:
    """The expected identity of one dispatch's deliverable, generated before the child runs."""
    return ":".join(
        (
            ARTIFACT_BINDING_PREFIX,
            _safe_component(run_id, label="run_id"),
            _safe_component(row_id, label="row_id"),
            _safe_component(nonce, label="nonce"),
        )
    )


def artifact_landing(landing_cwd: Path, run_id: str, row_id: str) -> Path:
    """Return the child's exclusive artifact directory inside its own landing.

    It lives *inside the landing* rather than beside the repository so a sandboxed mutating child
    can write to it at all, and it is required to be invisible to Git so two read-only children
    sharing one checkout stop being attributed each other's output.
    """
    return (
        register_store.orchestrate_dir(landing_cwd)
        .joinpath(*ARTIFACTS_SEGMENTS)
        .joinpath(_safe_component(run_id, label="run_id"), _safe_component(row_id, label="row_id"))
    )


def _path_state(path: Path) -> dict[str, Any]:
    """A comparable record of what is at ``path`` right now, symlinks not followed."""
    try:
        stat = path.lstat()
    except FileNotFoundError:
        return {"exists": False}
    if not os.path.isfile(path) or os.path.islink(path):
        return {"exists": True, "kind": "not-a-regular-file", "mode": stat.st_mode}
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        while chunk := stream.read(1024 * 1024):
            digest.update(chunk)
    return {
        "exists": True,
        "kind": "file",
        "size": stat.st_size,
        "digest": "sha256:" + digest.hexdigest(),
    }


def baseline_digest(baseline: session_lifecycle.ChangedPathsBaseline) -> str:
    """Digest a changed-paths baseline so a receipt can bind the snapshot it was issued against.

    A baseline is the one deciding input that cannot be sealed as a label, because it is
    repository state *at an instant* rather than a name: the same landing has different, equally
    valid snapshots before and after a write.  Binding the landing therefore says nothing about
    *when* the snapshot was taken, and an out-of-scope write verifies cleanly against a baseline
    taken after it.  A digest is the smallest thing that makes substitution detectable.
    """
    digest = hashlib.sha256()
    for label, paths, fingerprints in (
        ("landing", baseline.paths, baseline.fingerprints),
        ("ambient", baseline.ambient_paths, baseline.ambient_fingerprints),
    ):
        digest.update(b"\0" + label.encode("utf-8"))
        for path in sorted(paths):
            digest.update(b"\0p" + path.encode("utf-8"))
        for path, fingerprint in sorted(fingerprints):
            digest.update(b"\0f" + path.encode("utf-8") + b"\0" + fingerprint.encode("utf-8"))
    digest.update(b"\0base\0" + (baseline.ambient_base_commit or "").encode("utf-8"))
    return "sha256:" + digest.hexdigest()


@dataclass(frozen=True)
class DispatchReceipt:
    """The expected identity of one dispatch's evidence, established before the child runs.

    "Identity" here means **every input the evaluator branches on**, not the labels that name the
    dispatch.  Binding run, row and landing stops one child's evidence verifying another child's
    row, and stops nothing else: the work shape decides whether the depth gate runs at all, the
    declared scope and mutability decide what the boundary check permits, and the baseline decides
    what "changed" means.  Each of those arrives as a separate argument, so each is sealed here and
    compared before evaluation.

    ``root`` is on that list for a reason worth stating, because it was the last member to be
    found.  Enumerating what a function reads by collecting its attribute reads -- ``spec.``
    something, ``landing.`` something -- cannot see a plain parameter, and ``root`` is a plain
    parameter.  It is also the input that decides *which register receives the answer*, so evidence
    issued against one repository could record a pass in a second one while the artifact settled in
    the first.  The per-run secret does not cover this incidentally: it is named for the run alone
    and lives outside every repository, so it authenticates the same receipt under either root.
    """

    root: str
    run_id: str
    row_id: str
    landing_cwd: str
    artifact_relpath: str
    binding_token: str
    nonce: str
    destination_state: dict[str, Any]
    predicate: PredicateSpec
    predicate_closure: tuple[str, ...]
    predicate_digest: str
    write_scope: tuple[str, ...]
    integration_mode: str
    destination: str
    destination_pre_state: dict[str, Any]
    base_commit: str | None
    issued_at: float
    runtime: str
    work_shape: str
    mutating: bool
    scope: tuple[str, ...]
    ambient_root: str | None
    baseline_digest: str
    run_root: str | None = None

    @property
    def artifact_path(self) -> Path:
        return Path(self.landing_cwd) / self.artifact_relpath

    @property
    def inflight_path(self) -> Path:
        return self.artifact_path.with_name(self.artifact_path.name + INFLIGHT_SUFFIX)

    def to_mapping(self) -> dict[str, Any]:
        return {
            "root": self.root,
            "run_id": self.run_id,
            "row_id": self.row_id,
            "landing_cwd": self.landing_cwd,
            "artifact_relpath": self.artifact_relpath,
            "binding_token": self.binding_token,
            "nonce": self.nonce,
            "destination_state": self.destination_state,
            "predicate": self.predicate.to_mapping(),
            "predicate_closure": list(self.predicate_closure),
            "predicate_digest": self.predicate_digest,
            "write_scope": list(self.write_scope),
            "integration_mode": self.integration_mode,
            "destination": self.destination,
            "destination_pre_state": self.destination_pre_state,
            "base_commit": self.base_commit,
            "issued_at": self.issued_at,
            "runtime": self.runtime,
            "work_shape": self.work_shape,
            "mutating": self.mutating,
            "scope": list(self.scope),
            "ambient_root": self.ambient_root,
            "baseline_digest": self.baseline_digest,
            "run_root": self.run_root,
        }

    @classmethod
    def from_mapping(cls, value: Mapping[str, Any]) -> DispatchReceipt:
        return cls(
            root=str(value["root"]),
            run_id=str(value["run_id"]),
            row_id=str(value["row_id"]),
            landing_cwd=str(value["landing_cwd"]),
            artifact_relpath=str(value["artifact_relpath"]),
            binding_token=str(value["binding_token"]),
            nonce=str(value["nonce"]),
            destination_state=dict(value["destination_state"]),
            predicate=PredicateSpec.from_mapping(value["predicate"]),
            predicate_closure=tuple(str(item) for item in value["predicate_closure"]),
            predicate_digest=str(value["predicate_digest"]),
            write_scope=tuple(str(item) for item in value["write_scope"]),
            integration_mode=str(value["integration_mode"]),
            destination=str(value["destination"]),
            destination_pre_state=dict(value["destination_pre_state"]),
            base_commit=(
                str(value["base_commit"]) if value.get("base_commit") is not None else None
            ),
            issued_at=float(value["issued_at"]),
            runtime=str(value["runtime"]),
            work_shape=str(value["work_shape"]),
            mutating=bool(value["mutating"]),
            scope=tuple(str(item) for item in value["scope"]),
            ambient_root=(
                str(value["ambient_root"]) if value.get("ambient_root") is not None else None
            ),
            baseline_digest=str(value["baseline_digest"]),
            run_root=(str(value["run_root"]) if value.get("run_root") is not None else None),
        )


def write_scope_for(
    spec: session_lifecycle.ChildSpec, landing: session_lifecycle.Landing
) -> tuple[str, ...]:
    """Every location this child may write, as landing-relative paths.

    A mutating child may write its declared scope inside its own worktree.  A read-only child may
    write **nothing** in the repository: its declared scope is a *read* scope, and treating it as a
    write allowlist is what made two well-behaved read-only children in one checkout each classify
    the other a boundary violator.  Every child, of either kind, may write its own exclusive
    artifact directory.
    """
    artifacts = artifact_landing(Path(landing.cwd), spec.run_id, spec.row_id)
    relative = artifacts.resolve().relative_to(Path(landing.cwd).resolve()).as_posix()
    declared = session_lifecycle.normalize_scope(spec.scope) if spec.mutating else ()
    return tuple(dict.fromkeys((*declared, relative)))


def repository_scope_for(spec: session_lifecycle.ChildSpec) -> session_lifecycle.ChildSpec:
    """Return the spec whose ``scope`` is the child's repository *write* allowlist.

    For a read-only child that allowlist is empty, so any repository-visible change fails the
    boundary check regardless of which child made it -- and a correct read-only child makes none,
    because its artifact lands outside Git's view.
    """
    if spec.mutating:
        return spec
    return replace(spec, scope=())


def assert_landing_is_invisible_to_git(
    landing_cwd: Path,
    artifacts_dir: Path,
    *,
    git: session_lifecycle.GitLanding,
) -> None:
    """Fail closed unless the artifact landing is ignored by the repository.

    The read-only sibling repair rests on artifacts being outside the Git boundary.  That is a
    property of the repository's state, not of this code, so it is checked rather than assumed: in
    a repository that does not ignore the orchestrate state directory, artifacts would be
    repository-visible and concurrent read-only children would attribute each other's output
    again.

    "Outside the boundary" is not the same question as "matched by an ignore rule".  An operator
    who force-adds an artifact from an earlier run leaves a *tracked* path under an ignored
    directory, and every later settle of that path is then reported as a repository change -- so
    the control would fire on the orchestrator's own rename.  Refusing at issue time, before any
    child is dispatched, turns that into one actionable message instead of a child that fails
    every attempt.
    """
    relative = artifacts_dir.resolve().relative_to(landing_cwd.resolve()).as_posix()
    if not git.is_invisible_to_boundary(landing_cwd, relative):
        raise LandingNotExclusiveError(
            f"{relative} is not invisible to the repository at {landing_cwd}: it is either not "
            "ignored or already tracked. The per-child artifact landing must be outside the "
            "boundary check, otherwise concurrent children are attributed each other's artifacts "
            "and the orchestrator's own settle is read as a child write. If it is tracked, "
            f"'git rm -r --cached {relative}' clears it."
        )


def _repository_common_dir(git: session_lifecycle.GitLanding, path: Path) -> Path:
    """The git object store that contains ``path``, or raise if Git cannot name one.

    Catches :class:`session_lifecycle.SessionLifecycleError`, not only ``LandingError``.
    Git returning non-zero is a ``LandingError``. Git not running at all -- missing
    binary, missing path, timeout -- is the parent class, and is not a
    :class:`CompletionError` unless converted here.
    """
    try:
        return git.common_dir(path)
    except session_lifecycle.SessionLifecycleError as exc:
        raise ReceiptRootError(
            f"cannot establish which repository {path} belongs to: {exc}"
        ) from exc


def _same_repository(git: session_lifecycle.GitLanding, cwd: Path, store: Path) -> bool:
    """True when ``cwd`` and ``store`` share a git object store.

    This is repository membership. It is not "the store contains the work". Each side
    is asked independently. Asking both from the same directory, or comparing the
    relative string ``.git`` that every repository reports, would make two repositories
    compare equal.
    """
    return _repository_common_dir(git, cwd) == _repository_common_dir(git, store)


def _store_contains_work(cwd: Path, store: Path) -> bool:
    """True when ``cwd`` is ``store`` or a descendant, after resolving both.

    This is "the store contains the work". It is not repository membership. A nested
    independent repository is a descendant and a different repository; a sibling
    linked worktree shares the object store and does not contain the main checkout.
    """
    return cwd.resolve().is_relative_to(store.resolve())


def assert_landing_belongs_to_store(
    landing: session_lifecycle.Landing,
    store: Path,
    *,
    git: session_lifecycle.GitLanding,
) -> None:
    """Refuse a landing that does not belong in ``store`` as a register.

    Two properties, not one check with two clauses. Git identity asks whether the
    working directory and the store are the same repository. Containment asks whether
    the store contains the work. Either one alone accepts pairings the other refuses.
    """
    cwd = Path(landing.cwd).resolve()
    resolved = Path(store).resolve()
    if not _same_repository(git, cwd, resolved):
        raise ReceiptRootError(
            f"the landing at {cwd} does not belong to the repository at {resolved}; a "
            "receipt sealed from those two fields would agree with itself and record the "
            "verdict where the work did not happen"
        )
    if not _store_contains_work(cwd, resolved):
        raise ReceiptRootError(
            f"the landing at {cwd} is not inside the store at {resolved}; a worktree has "
            "its own register, so a store that does not contain the work files a verdict "
            "where nothing else about the run is recorded"
        )


def landing_root(landing: session_lifecycle.Landing, *, git: session_lifecycle.GitLanding) -> Path:
    """The store a landing names, after it is shown to belong there.

    ``GitLanding.provision`` sets ``ambient_root`` to the repository root for both landing kinds --
    a read-only child lands in the ambient checkout and a mutating child lands in a worktree of it
    -- so the landing already knows its store and a caller never has to say it a second time.

    A landing built by hand with no ``ambient_root`` is refused rather than defaulted to ``cwd``.
    Defaulting would silently seal a mutating child's *worktree* as its work location, and
    retirement would archive into the worktree rather than the checkout the run is tracked in.

    Two properties are checked, and they are not the same question. Git identity refuses a
    nested independent repository, which is a descendant path and a different store.
    Containment refuses a store that does not contain the work -- a sibling worktree, another
    worktree of the same repository, a subdirectory named as the store.

    A working directory that is an ordinary subdirectory of the *same* store is still
    accepted. A store that is an ancestor of a mutating child's worktree and shares its
    object store is still accepted **when no run root has been recorded**; five such
    ancestors exist and only one is the run's register. The recorded run root is what
    picks that one. This function does not record it.
    """
    if landing.ambient_root is None:
        raise ReceiptRootError(
            f"the landing at {landing.cwd} does not name the repository it belongs to; a receipt "
            "records where its own verdict lands, so it cannot be issued against a landing whose "
            "repository is unknown"
        )
    root = Path(landing.ambient_root).resolve()
    assert_landing_belongs_to_store(landing, root, git=git)
    return root


def issue_receipt(
    spec: session_lifecycle.ChildSpec,
    landing: session_lifecycle.Landing,
    predicate: PredicateSpec,
    *,
    artifact_name: str,
    git: session_lifecycle.GitLanding,
    changed_paths_baseline: session_lifecycle.ChangedPathsBaseline,
    nonce: str | None = None,
) -> DispatchReceipt:
    """Establish this dispatch's expected evidence identity **before** the child is dispatched.

    Everything a later comparison relies on is computed here: the run-binding token, the
    destination's pre-dispatch state, the predicate's dependency closure and its content digest,
    and the destination-integration pre-state.  None of it is read from beside the artifact later,
    because a stale record in the child's own output directory would satisfy a comparison against
    itself.

    The durable copy is **sealed** with this run's orchestrator secret (see :func:`run_secret`).
    The live register sits outside every landing, but Claude and Muse have no workspace-write
    flag, so those runtimes can still reach the host-local file.  ``artifact_path`` is
    deliberately *not* written here: the
    already-shipping catch-up consumer treats a declared artifact path that does not exist as an
    operator-attention signal, and at issue time the artifact is required to be absent.  It is
    recorded once settlement has actually happened, as an absolute path, because that consumer
    resolves a relative path against the ambient checkout while a mutating child's artifact lives
    in its worktree.

    ``changed_paths_baseline`` is taken by U4's readiness path and passed in rather than taken
    here, deliberately: two takers of one snapshot is the same shape as two writers of one register
    column, and that shape is what let a mutation survive undetected in the previous round.  One
    producer (readiness), one binder (this function), one comparison (evaluation).

    **The repository is derived from the landing, not accepted from the caller.**  This function is
    the *first* observation of where the verdict belongs, so a root supplied here has nothing to be
    compared against -- and every downstream check compares a supplied root with the copy made from
    that same value here, which is not a check of it.  A separate root parameter could therefore be
    wrong in the one place no later control could ever notice: a receipt sealed under repository B
    carrying a landing in repository A passed every comparison and recorded the pass in B while the
    work happened in A.  Deriving it removes that parameter.  It does not remove the pair on the
    landing itself -- ``cwd`` and ``ambient_root`` remain independently settable -- so
    :func:`landing_root` also refuses a landing that fails git identity or containment.  This
    function then compares the derived store to the run root recorded at launch -- a value
    whose provenance is not the landing -- and writes the store (the sealed receipt, and it
    clears any earlier settlement) before any evaluation exists, so an evaluate-time-only
    check is already too late.  This function never records the run root.
    """
    root = landing_root(landing, git=git)
    assert_store_is_this_runs_register(root, spec.run_id)
    recorded = read_run_root(spec.run_id)
    landing_cwd = Path(landing.cwd).resolve()
    artifacts = artifact_landing(landing_cwd, spec.run_id, spec.row_id)
    assert_landing_is_invisible_to_git(landing_cwd, artifacts, git=git)
    artifacts.mkdir(parents=True, exist_ok=True)

    name = _safe_component(artifact_name, label="artifact_name")
    artifact_relpath = (artifacts / name).relative_to(landing_cwd).as_posix()

    scope = write_scope_for(spec, landing)
    closure = predicate_closure(landing_cwd, predicate, subject=artifact_relpath)
    assert_predicate_outside_write_scope(closure, scope)

    resolved_nonce = nonce or uuid.uuid4().hex
    token = artifact_binding_token(spec.run_id, spec.row_id, resolved_nonce)

    receipt = DispatchReceipt(
        root=str(root),
        run_id=spec.run_id,
        row_id=spec.row_id,
        landing_cwd=str(landing_cwd),
        artifact_relpath=artifact_relpath,
        binding_token=token,
        nonce=resolved_nonce,
        destination_state=_path_state(landing_cwd / artifact_relpath),
        predicate=predicate,
        predicate_closure=closure,
        predicate_digest=closure_digest(landing_cwd, predicate, closure),
        write_scope=scope,
        integration_mode=landing.integration_mode,
        destination=landing.destination,
        destination_pre_state=_integration_pre_state(landing, git=git),
        base_commit=landing.base_commit,
        issued_at=time.time(),
        runtime=spec.runtime,
        work_shape=spec.work_shape,
        mutating=spec.mutating,
        scope=session_lifecycle.normalize_scope(spec.scope),
        ambient_root=_resolved_or_none(landing.ambient_root),
        baseline_digest=baseline_digest(changed_paths_baseline),
        run_root=str(recorded) if recorded is not None else None,
    )
    register_store.upsert_row(
        root,
        spec.row_id,
        {
            "run_id": spec.run_id,
            "predicate": predicate.to_mapping(),
            DISPATCH_RECEIPT_KEY: _seal(receipt.to_mapping(), run_secret(root, spec.run_id)),
            # A new dispatch supersedes any earlier attempt's settlement for this row.
            SETTLEMENT_KEY: None,
        },
        run_id=spec.run_id,
    )
    return receipt


def _resolved_or_none(path: Path | None) -> str | None:
    return str(path.resolve()) if path is not None else None


def _integration_pre_state(
    landing: session_lifecycle.Landing,
    *,
    git: session_lifecycle.GitLanding,
) -> dict[str, Any]:
    if landing.integration_mode == "branch":
        ambient = Path(landing.ambient_root or landing.cwd)
        return {"commit": git.rev_parse(ambient, landing.destination)}
    if landing.integration_mode == "path":
        ambient = Path(landing.ambient_root or landing.cwd)
        return _path_state(ambient / landing.destination)
    return {}


def artifact_instructions(receipt: DispatchReceipt) -> str:
    """The dispatch text that makes a child's output settleable and bindable.

    The child never writes the destination.  It writes the in-flight sibling, and this module
    renames.  That is why "the predicate accepts only the renamed path" is enforceable at all.
    """
    return (
        "Write your deliverable to this exact path and to no other path:\n"
        f"  {receipt.inflight_path}\n"
        "Do not create or modify:\n"
        f"  {receipt.artifact_path}\n"
        "The orchestrator renames the in-flight file into place once you stop; a deliverable "
        "written directly to the destination is rejected.\n"
        "Include this line verbatim somewhere in the deliverable, on its own line:\n"
        f"  {receipt.binding_token}\n"
    )


