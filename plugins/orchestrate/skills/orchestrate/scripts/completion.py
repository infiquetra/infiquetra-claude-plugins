def is_judgment_shaped(work_shape: str) -> bool:
    """Classify through U1's authoritative vocabulary, including its role-tier aliases."""
    canonical = tier_resolver.ROLE_TIER_ALIASES.get(work_shape, work_shape)
    return canonical in JUDGMENT_WORK_SHAPES


@dataclass(frozen=True)
class SampledClaim:
    claim: str
    evidence_location: str
    disposition: str

    def __post_init__(self) -> None:
        if not self.claim.strip():
            raise DepthSampleError("a sampled claim must name the claim it sampled")
        if not self.evidence_location.strip():
            raise DepthSampleError(
                f"sampled claim {self.claim!r} must record where its evidence was checked"
            )
        if self.disposition not in DEPTH_DISPOSITIONS:
            raise DepthSampleError(
                f"disposition {self.disposition!r} is not one of {DEPTH_DISPOSITIONS}"
            )

    def to_mapping(self) -> dict[str, str]:
        return {
            "claim": self.claim,
            "evidence_location": self.evidence_location,
            "disposition": self.disposition,
        }


@dataclass(frozen=True)
class DepthSample:
    """One independent verifier's blind read of a judgment-shaped child's artifact."""

    verifier_row_id: str
    verifier_vendor: str
    verifier_model: str
    artifact_digest: str
    claims: tuple[SampledClaim, ...]

    def to_mapping(self) -> dict[str, Any]:
        return {
            "verifier_row_id": self.verifier_row_id,
            "verifier_vendor": self.verifier_vendor,
            "verifier_model": self.verifier_model,
            "artifact_digest": self.artifact_digest,
            "claims": [claim.to_mapping() for claim in self.claims],
        }

    @classmethod
    def from_mapping(cls, value: Mapping[str, Any]) -> DepthSample:
        claims = value.get("claims")
        if not isinstance(claims, Sequence) or isinstance(claims, str):
            raise DepthSampleError("a depth sample must carry a claims array")
        return cls(
            verifier_row_id=str(value["verifier_row_id"]),
            verifier_vendor=str(value["verifier_vendor"]),
            verifier_model=str(value["verifier_model"]),
            artifact_digest=str(value["artifact_digest"]),
            claims=tuple(
                SampledClaim(
                    str(item["claim"]),
                    str(item["evidence_location"]),
                    str(item["disposition"]),
                )
                for item in claims
                if isinstance(item, Mapping)
            ),
        )

    def validate(self, *, child_row_id: str, artifact_digest: str) -> None:
        """Check what a record *can* establish: independence, binding, and completeness.

        Independence is enforced by identity: a verifier that is the child cannot be a second
        reader.  Binding to this artifact is enforced by digest, so a sample recorded against some
        other document cannot be presented as a read of this one.  Blindness -- that the verifier
        saw the artifact and not the child's own account of it -- is a property of how the verifier
        was dispatched and is *not* provable from this record; the dispatch contract in
        ``references/predicates.md`` owns it.
        """
        if not self.verifier_row_id or self.verifier_row_id == child_row_id:
            raise DepthSampleError(
                "a depth sample must come from a verifier session other than the child itself; "
                f"got {self.verifier_row_id!r} for child {child_row_id!r}"
            )
        if self.artifact_digest != artifact_digest:
            raise DepthSampleError(
                "the depth sample is recorded against a different artifact "
                f"({self.artifact_digest} != {artifact_digest}); it is not a read of this "
                "dispatch's evidence"
            )
        if not self.claims:
            raise DepthSampleError("a depth sample must record at least one sampled claim")


# --------------------------------------------------------------------------- evaluation


@dataclass(frozen=True)
class CompletionResult:
    row_id: str
    verified: bool
    reason: str
    detail: str
    predicate: PredicateOutcome | None = None
    scope: session_lifecycle.ScopeCheck | None = None
    artifact_digest: str | None = None
    integration: str | None = None

    def to_mapping(self) -> dict[str, Any]:
        return {
            "result": "verified" if self.verified else "failed",
            "reason": self.reason,
            "detail": self.detail,
            "predicate": self.predicate.to_mapping() if self.predicate is not None else None,
            "artifact_digest": self.artifact_digest,
            "integration": self.integration,
            "at": time.time(),
        }


def _record(root: Path, row_id: str, result: CompletionResult) -> CompletionResult:
    """Write the durable verdict.

    The verdict lives in its own ``completion`` key rather than in ``observed_state``.
    ``observed_state`` is owned by the liveness detectors: the subscriber's snapshot catch-up
    rewrites it for every row with a live pane, so a failure recorded only there is erased the
    next time catch-up runs while the child's pane is still open.  ``phase`` is advanced to
    ``verified`` **only** on a full pass; a failed predicate leaves the phase exactly where it was,
    because ``PHASES`` is a closed, operator-approved vocabulary with no member meaning "evaluated
    and failed" and inventing one is not this unit's call.  The register still distinguishes a
    failed child from a working one, which is what the operator's only view requires.
    """
    fields: dict[str, Any] = {"completion": result.to_mapping()}
    if result.verified:
        fields["phase"] = "verified"
        fields["expected_state"] = "verified"
    register_store.upsert_row(root, row_id, fields)
    return result


def evaluate_completion(
    root: Path,
    spec: session_lifecycle.ChildSpec,
    landing: session_lifecycle.Landing,
    changed_paths_baseline: session_lifecycle.ChangedPathsBaseline,
    receipt: DispatchReceipt,
    *,
    git: session_lifecycle.GitLanding,
    depth_sample: DepthSample | Mapping[str, Any] | None = None,
) -> CompletionResult:
    """Decide whether one child reaches ``verified``, and record why either way."""
    landing_cwd = Path(landing.cwd)

    current_digest = closure_digest(landing_cwd, receipt.predicate, receipt.predicate_closure)
    if current_digest != receipt.predicate_digest:
        return _record(
            root,
            spec.row_id,
            CompletionResult(
                spec.row_id,
                False,
                "predicate_tampered",
                "the predicate's dependency closure changed between dispatch and evaluation; "
                f"expected {receipt.predicate_digest}, found {current_digest}",
            ),
        )

    try:
        artifact = settle_artifact(receipt)
    except ArtifactError as exc:
        return _record(
            root, spec.row_id, CompletionResult(spec.row_id, False, "artifact_unsettled", str(exc))
        )

    try:
        artifact_digest = assert_artifact_binding(artifact, receipt)
    except ArtifactError as exc:
        return _record(
            root, spec.row_id, CompletionResult(spec.row_id, False, "artifact_binding", str(exc))
        )

    observer_baseline = git.changed_paths_baseline(
        landing_cwd,
        base_commit=landing.base_commit,
        ambient_root=landing.ambient_root,
    )
    outcome = run_predicate(receipt.predicate, workdir=landing_cwd)
    disturbed = _predicate_side_effects(landing, observer_baseline, git=git)
    if disturbed:
        return _record(
            root,
            spec.row_id,
            CompletionResult(
                spec.row_id,
                False,
                "predicate_side_effect",
                "the predicate changed the child's landing while evaluating it, so the boundary "
                "evidence is no longer attributable: " + ", ".join(sorted(disturbed)),
                predicate=outcome,
                artifact_digest=artifact_digest,
            ),
        )

    scope_check: session_lifecycle.ScopeCheck | None = None
    try:
        scope_check = session_lifecycle.check_completion_scope(
            repository_scope_for(spec),
            landing,
            changed_paths_baseline,
            predicate_passed=outcome.passed,
            git=git,
        )
    except session_lifecycle.ScopeViolationError as exc:
        return _record(
            root,
            spec.row_id,
            CompletionResult(
                spec.row_id,
                False,
                "scope_violation",
                str(exc),
                predicate=outcome,
                artifact_digest=artifact_digest,
            ),
        )

    if not outcome.passed:
        return _record(
            root,
            spec.row_id,
            CompletionResult(
                spec.row_id,
                False,
                outcome.reason,
                f"predicate {list(receipt.predicate.argv)} did not pass: {outcome.reason}",
                predicate=outcome,
                scope=scope_check,
                artifact_digest=artifact_digest,
            ),
        )

    try:
        integration = verify_integration(receipt, landing, git=git)
    except CompletionError as exc:
        return _record(
            root,
            spec.row_id,
            CompletionResult(
                spec.row_id,
                False,
                "integration_unverified",
                str(exc),
                predicate=outcome,
                scope=scope_check,
                artifact_digest=artifact_digest,
            ),
        )

    depth_failure = _depth_verdict(spec, depth_sample, artifact_digest=artifact_digest)
    if depth_failure is not None:
        reason, detail = depth_failure
        return _record(
            root,
            spec.row_id,
            CompletionResult(
                spec.row_id,
                False,
                reason,
                detail,
                predicate=outcome,
                scope=scope_check,
                artifact_digest=artifact_digest,
                integration=integration,
            ),
        )

    return _record(
        root,
        spec.row_id,
        CompletionResult(
            spec.row_id,
            True,
            "verified",
            f"settled, run-bound artifact {receipt.artifact_relpath} passed "
            f"{list(receipt.predicate.argv)}; {integration}",
            predicate=outcome,
            scope=scope_check,
            artifact_digest=artifact_digest,
            integration=integration,
        ),
    )


def _predicate_side_effects(
    landing: session_lifecycle.Landing,
    observer_baseline: session_lifecycle.ChangedPathsBaseline,
    *,
    git: session_lifecycle.GitLanding,
) -> set[str]:
    """Repository-visible paths the predicate itself touched, in the landing or the ambient tree.

    Compared against a snapshot taken immediately before the predicate ran, so anything reported
    here was authored by the check and not by the child.  Both trees are covered because a
    mutating child's predicate runs in its worktree while the ambient checkout is observed
    separately by the boundary check.
    """
    after = git.changed_paths_baseline(
        Path(landing.cwd),
        base_commit=landing.base_commit,
        ambient_root=landing.ambient_root,
    )
    return _differences(observer_baseline.fingerprints, after.fingerprints) | _differences(
        observer_baseline.ambient_fingerprints, after.ambient_fingerprints
    )


def _differences(before: Sequence[tuple[str, str]], after: Sequence[tuple[str, str]]) -> set[str]:
    before_map = dict(before)
    after_map = dict(after)
    return {
        path
        for path in set(before_map) | set(after_map)
        if before_map.get(path) != after_map.get(path)
    }


def _depth_verdict(
    spec: session_lifecycle.ChildSpec,
    depth_sample: DepthSample | Mapping[str, Any] | None,
    *,
    artifact_digest: str,
) -> tuple[str, str] | None:
    """Judgment-shaped work cannot reach verified on mechanical coverage alone."""
    if not is_judgment_shaped(spec.work_shape):
        return None
    if depth_sample is None:
        return (
            "depth_sample_missing",
            f"work shape {spec.work_shape!r} is judgment-shaped, so a passing mechanical "
            "predicate is not sufficient; an independent verifier's depth sample is required",
        )
    sample = (
        depth_sample
        if isinstance(depth_sample, DepthSample)
        else DepthSample.from_mapping(depth_sample)
    )
    try:
        sample.validate(child_row_id=spec.row_id, artifact_digest=artifact_digest)
    except DepthSampleError as exc:
        return "depth_sample_invalid", str(exc)
    unsupported = [claim for claim in sample.claims if claim.disposition == "unsupported"]
    if unsupported:
        return (
            "depth_sample_unsupported",
            "the independent verifier could not support "
            + "; ".join(f"{claim.claim!r} at {claim.evidence_location}" for claim in unsupported),
        )
    return None


def read_receipt(root: Path, row_id: str) -> DispatchReceipt:
    """Load the receipt this dispatch established, from the register rather than from disk."""
    row = register_store.read_rows(root).get(row_id)
    if row is None:
        raise CompletionError(f"unknown child row {row_id!r}")
    stored = row.get("dispatch_receipt")
    if not isinstance(stored, Mapping):
        raise CompletionError(
            f"child {row_id!r} has no dispatch receipt; it was never bound to a dispatch and "
            "cannot be completed"
        )
    return DispatchReceipt.from_mapping(stored)


def completion_record(root: Path, row_id: str) -> dict[str, Any] | None:
    """The operator-facing verdict for one row, or ``None`` when it has not been evaluated."""
    row = register_store.read_rows(root).get(row_id)
    if row is None:
        return None
    record = row.get("completion")
    return dict(record) if isinstance(record, Mapping) else None


def is_working_not_failed(root: Path, row_id: str) -> bool:
    """True when a row is still working rather than carrying a recorded failure.

    ``PHASES`` has no member for "evaluated and failed", so this is how the operator's view keeps
    the two apart without inventing one.
    """
    record = completion_record(root, row_id)
    return record is None or record.get("result") != "failed"


def failed_rows(root: Path, *, run_id: str | None = None) -> dict[str, dict[str, Any]]:
    """Every row whose recorded verdict is a failure -- the operator's "what stalled" view."""
    rows = register_store.read_rows(root, run_id=run_id)
    failed: dict[str, dict[str, Any]] = {}
    for row_id, row in rows.items():
        record = row.get("completion")
        if isinstance(record, Mapping) and record.get("result") == "failed":
            failed[row_id] = dict(record)
    return failed
