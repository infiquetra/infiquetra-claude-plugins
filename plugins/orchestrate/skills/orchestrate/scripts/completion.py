@dataclass(frozen=True)
class Settlement:
    """The durable fact that one dispatch's artifact was renamed into place, and what it was."""

    nonce: str
    artifact_relpath: str
    artifact_path: str
    digest: str
    settled_at: float

    def to_mapping(self) -> dict[str, Any]:
        return {
            "nonce": self.nonce,
            "artifact_relpath": self.artifact_relpath,
            "artifact_path": self.artifact_path,
            "digest": self.digest,
            "settled_at": self.settled_at,
        }

    @classmethod
    def from_mapping(cls, value: Mapping[str, Any]) -> Settlement:
        return cls(
            nonce=str(value["nonce"]),
            artifact_relpath=str(value["artifact_relpath"]),
            artifact_path=str(value["artifact_path"]),
            digest=str(value["digest"]),
            settled_at=float(value["settled_at"]),
        )


def settlement_record(root: Path, receipt: DispatchReceipt) -> Settlement | None:
    """The authenticated settlement recorded for this dispatch, or ``None`` if there is none.

    Sealed with the same run secret as the receipt and for the same reason: a child that could
    plant an unauthenticated settlement record could make this module replay a settlement that
    never happened, and so accept a file the child wrote straight to the destination.
    """
    row = register_store.read_rows(root).get(receipt.row_id)
    stored = row.get(SETTLEMENT_KEY) if row is not None else None
    if not isinstance(stored, Mapping):
        return None
    payload = _unseal(stored, run_secret(root, receipt.run_id, create=False), label="settlement")
    return Settlement.from_mapping(payload)


def settle_artifact(root: Path, receipt: DispatchReceipt) -> Settlement:
    """Rename the child's in-flight file into place, once, and record that it happened.

    Three refusals on a first settlement, each of which is a real observation rather than an
    inference about how a file was produced: the destination changed during the dispatch window
    (the child wrote it directly), no in-flight file exists (the child did not follow the protocol
    at all), or the in-flight path is not a regular file (a symlink would make the rename land
    content the child chose from elsewhere).

    **Why this is idempotent, and why that is not a convenience.**  Settlement is a one-shot
    rename: after it, the in-flight file is gone and the destination is present, which is
    byte-for-byte the state a child that wrote the destination directly would leave.  Nothing on
    disk distinguishes them.  So a *second* evaluation of a correct child -- which the catch-up
    contract requires on every startup and reconnect, and which judgment-shaped work requires
    because its verifier must read the *settled* artifact -- would fail as though the child had
    cheated.  The durable settlement record is what tells the two apart, and replaying it is what
    makes a second evaluation reach the same verdict as the first instead of a false failure.

    The replay is conditional on the destination still holding exactly the bytes that were
    settled.  If it changed afterwards, this is not a replay: the evidence on disk is no longer
    the evidence that was settled, and that fails.
    """
    recorded = settlement_record(root, receipt)
    destination = receipt.artifact_path
    if recorded is not None and recorded.nonce == receipt.nonce:
        current = _path_state(destination)
        if current.get("digest") == recorded.digest:
            return recorded
        raise ArtifactError(
            f"artifact {receipt.artifact_relpath} was settled at {recorded.settled_at:.0f} with "
            f"digest {recorded.digest} and no longer matches it; the evidence on disk is not the "
            "evidence that was settled"
        )
    inflight = receipt.inflight_path
    current = _path_state(destination)
    if current != receipt.destination_state:
        raise ArtifactError(
            f"artifact destination {receipt.artifact_relpath} changed during the dispatch window; "
            "a deliverable must be written to the in-flight sibling and renamed by the "
            "orchestrator, never written directly to the destination"
        )
    if not inflight.exists() or inflight.is_symlink() or not inflight.is_file():
        raise ArtifactError(
            f"no regular in-flight artifact at {inflight.name}; the child did not produce a "
            "settleable deliverable"
        )
    os.replace(inflight, destination)
    settlement = Settlement(
        nonce=receipt.nonce,
        artifact_relpath=receipt.artifact_relpath,
        artifact_path=str(destination),
        digest=str(_path_state(destination)["digest"]),
        settled_at=time.time(),
    )
    register_store.upsert_row(
        root,
        receipt.row_id,
        {
            SETTLEMENT_KEY: _seal(
                settlement.to_mapping(), run_secret(root, receipt.run_id, create=False)
            ),
            # The catch-up consumer resolves this against the ambient checkout, so it is absolute:
            # a mutating child's artifact lives in its worktree, not under the ambient root.
            "artifact_path": settlement.artifact_path,
        },
    )
    return settlement


def assert_artifact_binding(
    path: Path,
    receipt: DispatchReceipt,
    *,
    max_bytes: int = DEFAULT_MAX_ARTIFACT_BYTES,
) -> str:
    """Require the artifact to carry this dispatch's pre-established token; return its digest."""
    size = path.stat().st_size
    if size > max_bytes:
        raise ArtifactError(
            f"artifact {receipt.artifact_relpath} is {size} bytes, above the {max_bytes}-byte "
            "binding-check bound"
        )
    data = path.read_bytes()
    text = data.decode("utf-8", errors="replace")
    if receipt.binding_token not in text:
        raise ArtifactError(
            f"artifact {receipt.artifact_relpath} does not carry this dispatch's run binding "
            f"({_describe_foreign_bindings(text)}); it is not evidence produced for run "
            f"{receipt.run_id!r} child {receipt.row_id!r} nonce {receipt.nonce!r}"
        )
    return "sha256:" + hashlib.sha256(data).hexdigest()


def _describe_foreign_bindings(text: str) -> str:
    """Name the bindings that *are* present, so a stale artifact reports as stale."""
    found = [
        f"run={match.group(1)!r} child={match.group(2)!r} nonce={match.group(3)!r}"
        for match in list(_BINDING_RE.finditer(text))[:4]
    ]
    if not found:
        return "the artifact carries no run binding at all"
    return "the artifact carries a binding for " + "; ".join(found)


