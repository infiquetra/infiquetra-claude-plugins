#!/usr/bin/env python3
"""Completion: predicate evaluation, run binding, artifact settlement, integration, depth.

This module is the first consumer of :func:`session_lifecycle.check_completion_scope` and the
only place a child reaches ``verified``.  Evidence integrity is the highest-severity failure
category in this plugin because a false *pass* is indistinguishable from a true one downstream,
so every control here is written to fail closed and to claim only what it actually enforces.

What each control proves, and what it does not
----------------------------------------------
**Settlement is performed by the orchestrator, not asserted about the child.**  A file on disk
does not record whether it arrived by rename or by direct write -- ``stat`` does not carry it and
content does not carry it -- so a check that reads the finished artifact can never establish it.
Instead the child writes only to an *in-flight sibling* of the destination, and this module
performs the rename itself with :func:`os.replace`.  The destination is required to be
byte-for-byte the state recorded before dispatch, so a child that wrote the destination directly
is rejected with a real signal rather than a guess.  Because the in-flight path is a sibling of
the destination it is always on the same filesystem, so the rename is a rename and never a copy.
The predicate therefore only ever reads a path this module renamed into place.  Settlement is
recorded durably and replayed on a later evaluation of the same dispatch, because the rename is
one-shot: after it, "already settled correctly" and "written directly by the child" look identical
on disk, and only the record separates them.  What is **not** claimed: that the child produced the
in-flight file atomically.  A child that writes its in-flight file slowly is fine, because nothing
reads it until the rename.

**Run binding is established before dispatch and compared afterwards.**  The expected identity is
a token generated by the orchestrator before the child runs and stored in the register; the
artifact must carry that exact token.  It is never read from a file beside the artifact, because a
stale receipt from a previous run would then satisfy a comparison against itself.

**The durable records are authenticated, because the register is not a trusted store.**  Every
child can write files in its landing, the register is inside every child's landing, and it is
Git-ignored -- so the boundary check does not observe a child that rewrites it.  The dispatch
receipt and the settlement record therefore each carry a keyed digest under a per-run secret held
outside the repository (:func:`run_secret`).  A record the orchestrator did not write does not
authenticate, and nothing it claims is believed.  A child can still *delete* those records, and
then nothing verifies -- which is the correct failure.

**Predicate integrity is static and dynamic.**  Statically, the predicate's entry points *and its
resolvable import closure* -- including the parent package initializers Python executes on the way
to a submodule -- must lie outside everything the child may write.  Dynamically, a digest over the
closure's contents is captured before dispatch and re-checked before evaluation, so a change to
any statically known closure file is caught even if the file sits outside the child's declared
scope.  What is **not** covered is enumerated, member by member, in ``references/predicates.md``.

**The observer must not disturb the evidence.**  The predicate runs inline, in the child's
landing, after the child stopped.  Anything it writes there would otherwise be attributed to the
child by the boundary check, so the landing is snapshotted immediately before the predicate runs
and any predicate-authored change is a failure of the predicate, never of the child.  The
artifact directory is snapshotted alongside it, because that directory is deliberately invisible
to Git and an observer that cannot see the evidence is not observing the evidence.

Ordering
--------
Identity first: the specification, landing and receipt arrive as independent arguments, and a
receipt that belongs to a different child is refused before anything else is read.  Then evidence
integrity, short-circuiting (tamper, settlement, binding), because an unsettled or unbound
artifact is not evidence and there is nothing to evaluate.  Then the predicate outcome and the
boundary check, computed independently -- a boundary violation fails completion even when the
predicate passed.  Then integration, then the judgment-work depth sample.

Evaluation is re-runnable for one dispatch, and the phase follows the verdict: a row is
``verified`` if and only if its latest recorded verdict is a pass.
"""

