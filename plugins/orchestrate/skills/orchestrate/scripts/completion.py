@dataclass(frozen=True)
class PredicateOutcome:
    passed: bool
    reason: str
    returncode: int | None
    output: str

    def to_mapping(self) -> dict[str, Any]:
        return {
            "passed": self.passed,
            "reason": self.reason,
            "returncode": self.returncode,
            "output": self.output,
        }


def _predicate_env(pycache_dir: Path) -> dict[str, str]:
    """Keep a well-behaved Python predicate from writing bytecode into the child's landing."""
    env = dict(os.environ)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["PYTHONPYCACHEPREFIX"] = str(pycache_dir)
    return env


def run_predicate(
    predicate: PredicateSpec,
    *,
    workdir: Path,
    poll_seconds: float = 0.02,
) -> PredicateOutcome:
    """Run the check inline, bounded in time and output; every abnormal end is a failure.

    Output is streamed to a temporary file rather than a pipe so the byte cap can be enforced
    while the process is still running: a predicate that produces unbounded output is killed at
    the cap rather than buffered until it exhausts memory.
    """
    with tempfile.TemporaryDirectory(prefix="orchestrate-predicate-") as scratch:
        scratch_dir = Path(scratch)
        sink_path = scratch_dir / "output"
        deadline = time.monotonic() + predicate.timeout_seconds
        with sink_path.open("wb") as sink:
            try:
                process = subprocess.Popen(  # nosec B603 -- fixed argv sequence, shell never used
                    list(predicate.argv),
                    cwd=str(workdir),
                    stdout=sink,
                    stderr=subprocess.STDOUT,
                    env=_predicate_env(scratch_dir / "pycache"),
                )
            except (OSError, subprocess.SubprocessError) as exc:
                return PredicateOutcome(False, "predicate_error", None, f"{exc}")
            reason = ""
            while True:
                returncode = process.poll()
                if returncode is not None:
                    break
                if sink_path.stat().st_size > predicate.max_output_bytes:
                    reason = "predicate_output_limit"
                elif time.monotonic() >= deadline:
                    reason = "predicate_timeout"
                if reason:
                    process.kill()
                    process.wait()
                    break
                time.sleep(poll_seconds)
        output = _read_tail(sink_path, predicate.max_output_bytes)
        if reason:
            return PredicateOutcome(False, reason, None, output)
        if sink_path.stat().st_size > predicate.max_output_bytes:
            # A process that exits between two polls can still have breached the cap.
            return PredicateOutcome(False, "predicate_output_limit", process.returncode, output)
        if process.returncode != 0:
            return PredicateOutcome(False, "predicate_failed", process.returncode, output)
        return PredicateOutcome(True, "passed", 0, output)


def _read_tail(path: Path, limit: int) -> str:
    size = path.stat().st_size
    with path.open("rb") as stream:
        if size > limit:
            stream.seek(size - limit)
        return stream.read(limit).decode("utf-8", errors="replace")


# --------------------------------------------------------------------------- integration


def verify_integration(
    receipt: DispatchReceipt,
    landing: session_lifecycle.Landing,
    *,
    git: session_lifecycle.GitLanding,
) -> str:
    """Require the recorded destination to have actually moved before a child may be reaped.

    ``branch``: the destination branch must exist and its tip must differ from the commit the
    branch pointed at when the receipt was issued.  ``path``: the destination path's content must
    differ from its pre-dispatch state.  ``none``: read-only work integrates nowhere and there is
    nothing to verify -- that is the whole reason the mode exists, and it is stated rather than
    silently skipped.
    """
    mode = receipt.integration_mode
    if mode == "none":
        return "read-only artifact; integration mode 'none' has no destination to verify"
    ambient = Path(landing.ambient_root or landing.cwd)
    if mode == "branch":
        tip = git.rev_parse(ambient, receipt.destination)
        if tip is None:
            raise CompletionError(
                f"integration destination branch {receipt.destination!r} does not exist"
            )
        before = receipt.destination_pre_state.get("commit")
        if tip == before:
            raise CompletionError(
                f"integration destination branch {receipt.destination!r} is unchanged at {tip}; "
                "the child's work has not landed and reaping would discard it"
            )
        return f"branch {receipt.destination} advanced to {tip}"
    if mode == "path":
        current = _path_state(ambient / receipt.destination)
        if current == receipt.destination_pre_state:
            raise CompletionError(
                f"integration destination path {receipt.destination!r} is unchanged; the child's "
                "work has not landed and reaping would discard it"
            )
        return f"path {receipt.destination} changed"
    raise CompletionError(f"unsupported integration mode {mode!r}")


