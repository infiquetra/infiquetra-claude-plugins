def verify_integration(
    receipt: DispatchReceipt,
    landing: session_lifecycle.Landing,
    *,
    git: session_lifecycle.GitLanding,
) -> str:
    """Require the recorded destination to have actually moved before a child may be reaped.

    ``branch``: the destination branch must exist and its tip must differ from the commit the
    branch pointed at when the receipt was issued.  ``path``: the destination path's content must
    differ from its pre-dispatch state.  ``none``: read-only work integrates nowhere and there is
    nothing to verify -- that is the whole reason the mode exists, and it is stated rather than
    silently skipped.
    """
    mode = receipt.integration_mode
    if mode == "none":
        return "read-only artifact; integration mode 'none' has no destination to verify"
    ambient = Path(landing.ambient_root or landing.cwd)
    if mode == "branch":
        tip = git.rev_parse(ambient, receipt.destination)
        if tip is None:
            raise CompletionError(
                f"integration destination branch {receipt.destination!r} does not exist"
            )
        before = receipt.destination_pre_state.get("commit")
        if tip == before:
            raise CompletionError(
                f"integration destination branch {receipt.destination!r} is unchanged at {tip}; "
                "the child's work has not landed and reaping would discard it"
            )
        return f"branch {receipt.destination} advanced to {tip}"
    if mode == "path":
        current = _path_state(ambient / receipt.destination)
        if current == receipt.destination_pre_state:
            raise CompletionError(
                f"integration destination path {receipt.destination!r} is unchanged; the child's "
                "work has not landed and reaping would discard it"
            )
        return f"path {receipt.destination} changed"
    raise CompletionError(f"unsupported integration mode {mode!r}")


