@dataclass(frozen=True)
class SampledClaim:
    claim: str
    evidence_location: str
    disposition: str

    def __post_init__(self) -> None:
        if not self.claim.strip():
            raise DepthSampleError("a sampled claim must name the claim it sampled")
        if not self.evidence_location.strip():
            raise DepthSampleError(
                f"sampled claim {self.claim!r} must record where its evidence was checked"
            )
        if self.disposition not in DEPTH_DISPOSITIONS:
            raise DepthSampleError(
                f"disposition {self.disposition!r} is not one of {DEPTH_DISPOSITIONS}"
            )

    def to_mapping(self) -> dict[str, str]:
        return {
            "claim": self.claim,
            "evidence_location": self.evidence_location,
            "disposition": self.disposition,
        }


@dataclass(frozen=True)
class DepthSample:
    """A *claimed* independent read of a judgment-shaped child's artifact.

    The name of the thing and the proof behind it are not the same size, so the name says the
    smaller one.  :meth:`validate` establishes that the named verifier was **dispatched** for this
    run, with this vendor, under a receipt this orchestrator sealed and issued in this repository.
    It does not establish that the verifier ran: the phase and model it is checked against are
    register columns any write-capable actor can set.  Nor does anything establish that the read
    was blind -- that is a named non-enforcement, not an oversight.

    A later unit reading ``completion.depth_sample`` off a verified row is therefore reading a
    verifier's own report, with an authenticated dispatch standing behind who was asked to produce
    it.  That is a smaller guarantee than a proven independent read, and calling the object a
    blind read would assert the larger one.
    """

    verifier_row_id: str
    verifier_vendor: str
    verifier_model: str
    artifact_digest: str
    claims: tuple[SampledClaim, ...]

    def to_mapping(self) -> dict[str, Any]:
        return {
            "verifier_row_id": self.verifier_row_id,
            "verifier_vendor": self.verifier_vendor,
            "verifier_model": self.verifier_model,
            "artifact_digest": self.artifact_digest,
            "claims": [claim.to_mapping() for claim in self.claims],
        }

    @classmethod
    def from_mapping(cls, value: Mapping[str, Any]) -> DepthSample:
        """Parse an external depth mapping, raising :class:`DepthSampleError` for anything else.

        Every rejection is this one exception type on purpose.  This is the boundary where data
        that came from *outside* the orchestrator arrives, and the caller converts a
        ``DepthSampleError`` into a recorded ``depth_sample_invalid`` verdict.  A ``KeyError`` or a
        ``TypeError`` escaping here would instead take down the evaluation before anything is
        written, leaving a register that still shows the child working -- a control that raises
        instead of recording is a fail-open one level up.

        Claim entries are validated rather than filtered.  Silently skipping a non-mapping entry
        turns "one supported claim plus garbage" into a clean one-claim sample that can verify.
        """
        if not isinstance(value, Mapping):
            raise DepthSampleError("a depth sample must be a JSON object")
        claims = value.get("claims")
        if not isinstance(claims, Sequence) or isinstance(claims, str):
            raise DepthSampleError("a depth sample must carry a claims array")
        fields: dict[str, str] = {}
        for key in ("verifier_row_id", "verifier_vendor", "verifier_model", "artifact_digest"):
            item = value.get(key)
            if not isinstance(item, str) or not item.strip():
                raise DepthSampleError(f"a depth sample must carry a non-empty {key!r}")
            fields[key] = item
        parsed: list[SampledClaim] = []
        for index, item in enumerate(claims):
            if not isinstance(item, Mapping):
                raise DepthSampleError(f"sampled claim {index} is not a JSON object")
            missing = [
                key
                for key in ("claim", "evidence_location", "disposition")
                if not isinstance(item.get(key), str)
            ]
            if missing:
                raise DepthSampleError(f"sampled claim {index} is missing {sorted(missing)}")
            parsed.append(
                SampledClaim(
                    str(item["claim"]), str(item["evidence_location"]), str(item["disposition"])
                )
            )
        return cls(
            verifier_row_id=fields["verifier_row_id"],
            verifier_vendor=fields["verifier_vendor"],
            verifier_model=fields["verifier_model"],
            artifact_digest=fields["artifact_digest"],
            claims=tuple(parsed),
        )

    def validate(
        self,
        *,
        root: Path,
        child_row_id: str,
        run_id: str,
        artifact_digest: str,
    ) -> None:
        """Check what a record *can* establish: independence, binding, and completeness.

        Independence is enforced against the register, not against the sample.  A
        ``verifier_row_id`` that is merely a non-empty string different from the child's is not a
        session -- ``"verifier-that-does-not-exist"`` satisfies that test -- and "an independent
        verifier session" is the requirement.  So the named row must exist, must carry an
        authenticated dispatch for this run, must not be recorded as still waiting to start, and
        must be the vendor and model the sample claims it was.  What that reaches, and where it
        stops short of proving the verifier ran, is set out on
        :meth:`_assert_verifier_session`.

        Binding to this artifact is enforced by digest, so a sample recorded against some other
        document cannot be presented as a read of this one.

        Blindness -- that the verifier saw the artifact and not the child's own account of it --
        is a property of how the verifier was dispatched and is *not* provable from this record.
        Neither is vendor diversity between child and verifier: this module does not require them
        to differ.  Both are dispatch-contract obligations, owned by ``references/predicates.md``.
        """
        if not self.verifier_row_id or self.verifier_row_id == child_row_id:
            raise DepthSampleError(
                "a depth sample must come from a verifier session other than the child itself; "
                f"got {self.verifier_row_id!r} for child {child_row_id!r}"
            )
        if self.artifact_digest != artifact_digest:
            raise DepthSampleError(
                "the depth sample is recorded against a different artifact "
                f"({self.artifact_digest} != {artifact_digest}); it is not a read of this "
                "dispatch's evidence"
            )
        if not self.claims:
            raise DepthSampleError("a depth sample must record at least one sampled claim")
        self._assert_verifier_session(root, run_id=run_id)

    def _assert_verifier_session(self, root: Path, *, run_id: str) -> None:
        """Require the named verifier to be a dispatch this orchestrator authenticated.

        The register is not a trusted store -- that is the premise the dispatch receipt is sealed
        under -- so a check that reads only register *columns* certifies exactly what it distrusts.
        A write-capable child can plant a row with ``phase="working"`` and any vendor and model it
        likes, and a purely column-based check calls it a dispatched session.

        So the load-bearing requirement is an **authenticated dispatch receipt** for the verifier
        row, under this run's orchestrator secret.  A sandboxed child cannot produce that
        digest.  A same-account child whose sandbox does not deny the host-local directory
        can read the key and can.  The vendor is
        then compared against that sealed receipt rather than against the writable column.

        The receipt is loaded through :func:`read_receipt`, which enforces the repository the
        receipt was sealed under.  That matters here more than anywhere else: this is the one
        receipt the module fetches by row id instead of receiving as an argument, and the run
        secret is shared by run id across repositories, so without it an authentic verifier
        dispatch from another checkout authenticates in this one.

        **What this establishes, exactly: a verifier was dispatched in this repository, for this
        run, with this vendor.**  It does not establish that the verifier ran, and the wording is
        deliberate because the code cannot support the larger claim.  Two of the four things
        checked come from the sealed receipt (run, vendor); the other two are register columns that
        any write-capable actor can set:

        * ``phase`` -- read below to refuse a verifier that never got started.  It requires
          membership in ``PHASES_PAST_LAUNCH`` rather than refusing ``planned`` and ``launching``
          by name, because a check written as exclusions accepts everything it did not think of:
          ``""`` and a value that is not a phase at all both mean nothing started, and both read
          as started under a name-based refusal.  It refuses the *honest* never-ran state, which
          is a real and useful thing: a dispatch that failed to launch leaves ``planned`` and is
          caught.  It does not survive an adversary, because moving one column from ``planned`` to
          ``working`` is enough to present a verifier that was issued a genuine receipt and never
          read anything.
        * ``model`` -- resolved at launch, not carried on the receipt, so the model of a genuinely
          dispatched verifier can be misattributed.

        Sealing ``phase`` is not possible from inside this module.  The only evidence that separates
        "dispatched" from "ran" is observed *after* launch, and both observers live elsewhere: the
        launch transition is U4's and the liveness stream is U3's subscriber.  A real fix is an
        attestation written by one of those under the run secret, which is a change to those units,
        not to this one.

        This residual and the accepted one on the *child* row -- a child writing ``phase=verified``
        into its own row and being reaped with no completion record -- are the same defect against
        two different columns of the same untrusted store, and one authenticated-register change
        would close both.

        Nor does any of this establish blindness, or that the verifier's vendor differs from the
        child's.
        """
        row = register_store.read_rows(root, run_id=run_id).get(self.verifier_row_id)
        if row is None:
            raise DepthSampleError(
                f"the depth sample names verifier {self.verifier_row_id!r}, which has no row in "
                "the register; an independent verifier session is a session that was dispatched, "
                "not a string in a mapping"
            )
        try:
            verifier_receipt = read_receipt(root, self.verifier_row_id, run_id=run_id)
        except CompletionError as exc:
            raise DepthSampleError(
                f"verifier {self.verifier_row_id!r} carries no dispatch this orchestrator issued "
                f"({exc}); a register row alone is something the child can write, so it does not "
                "establish that a verifier session ever ran"
            ) from exc
        if verifier_receipt.run_id != run_id:
            raise DepthSampleError(
                f"verifier {self.verifier_row_id!r} was dispatched for run "
                f"{verifier_receipt.run_id!r}, not for this child's run {run_id!r}"
            )
        if verifier_receipt.runtime != self.verifier_vendor:
            raise DepthSampleError(
                f"the depth sample says verifier {self.verifier_row_id!r} is vendor "
                f"{self.verifier_vendor!r}, but its authenticated dispatch names "
                f"{verifier_receipt.runtime!r}"
            )
        phase = row.get("phase")
        if phase not in PHASES_PAST_LAUNCH:
            raise DepthSampleError(
                f"the register records verifier {self.verifier_row_id!r} at phase {phase!r}, which "
                f"is not one of the phases past launch {PHASES_PAST_LAUNCH!r}; a dispatch that "
                "never started cannot have read anything. This column is not sealed, so it refuses "
                "the honest never-started case, and any value outside the vocabulary, but not a "
                "planted one"
            )
        recorded_model = row.get("model")
        if not isinstance(recorded_model, str) or not recorded_model:
            raise DepthSampleError(
                f"verifier {self.verifier_row_id!r} has no recorded model; the sample's claim "
                "about who read the artifact cannot be checked"
            )
        if recorded_model != self.verifier_model:
            raise DepthSampleError(
                f"the depth sample says verifier {self.verifier_row_id!r} is model "
                f"{self.verifier_model!r}, but the register records {recorded_model!r}"
            )


